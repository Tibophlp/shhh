import AppKit
import Carbon.HIToolbox

/// Types text into the focused app by pasting it, then puts the user's clipboard back.
@MainActor
enum TextInserter {
    /// shortcut: a slow app can still read the clipboard after this, if one ever pastes the old clipboard, raise it.
    private static let restoreDelay: TimeInterval = 1.5

    static func insert(_ text: String) async {
        let pasteboard = NSPasteboard.general
        // Off the main thread: a lazily-provided clipboard makes its app render the data, which can hang.
        // nil (the copying app didn't answer) means there's nothing to put back.
        let saved = try? await runWithWatchdog(on: .global(qos: .userInitiated), timeout: 3) {
            snapshot(of: NSPasteboard.general)
        }
        // With Secure Input on (a password field, some terminals) the ⌘V may never arrive,
        // so the text stays on the clipboard for a manual paste instead of being thrown away.
        let keepOnClipboard = saved == nil || IsSecureEventInputEnabled()

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if !keepOnClipboard {
            // Tell clipboard managers to ignore this temporary entry.
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        }
        pasteboard.writeObjects([item])
        let changeCount = pasteboard.changeCount

        pressCommandV()

        guard !keepOnClipboard, let saved else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
            MainActor.assumeIsolated {
                // Only restore if nothing new was copied in the meantime.
                guard pasteboard.changeCount == changeCount else { return }
                restore(saved, to: pasteboard)
            }
        }
    }

    private static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let layout = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue()
        let key = layout.flatMap { commandKeyCode(for: "v", in: $0) } ?? CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    /// The key that types `character` with ⌘ held on `layout`: the V key sits elsewhere on Dvorak.
    nonisolated static func commandKeyCode(for character: String, in layout: TISInputSource) -> CGKeyCode? {
        guard let raw = TISGetInputSourceProperty(layout, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
        let modifiers = UInt32((cmdKey >> 8) & 0xFF)
        return data.withUnsafeBytes { bytes -> CGKeyCode? in
            guard let keyboard = bytes.bindMemory(to: UCKeyboardLayout.self).baseAddress else { return nil }
            for code in 0..<128 {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(keyboard, UInt16(code), UInt16(kUCKeyActionDown), modifiers,
                                            UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysBit),
                                            &deadKeys, chars.count, &length, &chars)
                if status == noErr, String(utf16CodeUnits: chars, count: length) == character { return CGKeyCode(code) }
            }
            return nil
        }
    }

    nonisolated private static func snapshot(of pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }
    }

    private static func restore(_ saved: [[NSPasteboard.PasteboardType: Data]], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !saved.isEmpty else { return }
        let items = saved.map { entry -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }
}
